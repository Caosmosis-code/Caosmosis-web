-- PostgreSQL schema used by Caosmosis' Spring/JPA backend.
-- `usuarios` is the authors table, `articulos` is the posts table, and `categoria`
-- is stored as a string on each article. Safe to run for a new database or an
-- existing installation; legacy comments become approved below.

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'LECTOR',
    bio TEXT,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    instagram VARCHAR(255),
    twitter VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS articulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    contenido TEXT NOT NULL,
    categoria VARCHAR(255) NOT NULL,
    autor_id BIGINT NOT NULL REFERENCES usuarios(id),
    fecha_publicacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    imagen_url VARCHAR(255),
    tiempo_lectura INTEGER,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    es_portada BOOLEAN NOT NULL DEFAULT FALSE,
    comentario_revision TEXT,
    fecha_publicacion_programada TIMESTAMP
);

CREATE TABLE IF NOT EXISTS comentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido TEXT NOT NULL,
    usuario_id BIGINT REFERENCES usuarios(id),
    autor_nombre VARCHAR(80),
    autor_email VARCHAR(180),
    articulo_id BIGINT NOT NULL REFERENCES articulos(id),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comentario_padre_id BIGINT REFERENCES comentarios(id),
    cantidad_likes INTEGER NOT NULL DEFAULT 0,
    estado VARCHAR(20) NOT NULL DEFAULT 'APROBADO'
);

CREATE TABLE IF NOT EXISTS likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id),
    visitor_key VARCHAR(36),
    comentario_id BIGINT NOT NULL REFERENCES comentarios(id),
    CONSTRAINT uk_like_user_comment UNIQUE (usuario_id, comentario_id),
    CONSTRAINT uk_like_visitor_comment UNIQUE (visitor_key, comentario_id)
);

-- Upgrade path for installations created before anonymous commenting.
ALTER TABLE comentarios ALTER COLUMN usuario_id DROP NOT NULL;
ALTER TABLE comentarios ADD COLUMN IF NOT EXISTS autor_nombre VARCHAR(80);
ALTER TABLE comentarios ADD COLUMN IF NOT EXISTS autor_email VARCHAR(180);
ALTER TABLE comentarios ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'APROBADO';
ALTER TABLE likes ALTER COLUMN usuario_id DROP NOT NULL;
ALTER TABLE likes ADD COLUMN IF NOT EXISTS visitor_key VARCHAR(36);

CREATE INDEX IF NOT EXISTS idx_articulos_categoria_fecha ON articulos (categoria, fecha_publicacion DESC);
CREATE INDEX IF NOT EXISTS idx_comentarios_post_state_date ON comentarios (articulo_id, estado, fecha);
